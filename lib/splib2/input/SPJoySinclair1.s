	.module SPJoySinclair1
	.globl SPJoySinclair1
	.globl SPtbllookup

; JoySinclair1
;
; Reads Sinclair 1 joystick (keys 6..0).
;
; exit:   a = F111RLDU active low
; uses:   af, de

SPJoySinclair1:
	ld a, #0xef
	in a, (#0xfe)
	and #0x1f; 000LRDUF active low
	ld de, #sinc1tbl; use table to transform
	jp SPtbllookup

sinc1tbl:
	.db 0x70,0xf0,0x71,0xf1
	.db 0x72,0xf2,0x73,0xf3
	.db 0x78,0xf8,0x79,0xf9
	.db 0x7a,0xfa,0x7b,0xfb
	.db 0x74,0xf4,0x75,0xf5
	.db 0x76,0xf6,0x77,0xf7
	.db 0x7c,0xfc,0x7d,0xfd
	.db 0x7e,0xfe,0x7f,0xff
