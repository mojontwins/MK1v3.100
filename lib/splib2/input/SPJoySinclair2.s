	.module SPJoySinclair2
	.globl SPJoySinclair2
	.globl SPtbllookup

; JoySinclair2
;
; Reads Sinclair 2 joystick (keys 1..5).
;
; exit:   a = F111RLDU active low
; uses:   af, de

SPJoySinclair2:
	ld a, #0xf7; key row 1..5
	in a, (#0xfe)
	and #0x1f; 000FUDRL active low
	ld de, #sinc2tbl; use table to transform
	jp SPtbllookup

sinc2tbl:
	.db 0x70,0x74,0x78,0x7c
	.db 0x72,0x76,0x7a,0x7e
	.db 0x71,0x75,0x79,0x7d
	.db 0x73,0x77,0x7b,0x7f
	.db 0xf0,0xf4,0xf8,0xfc
	.db 0xf2,0xf6,0xfa,0xfe
	.db 0xf1,0xf5,0xf9,0xfd
	.db 0xf3,0xf7,0xfb,0xff
